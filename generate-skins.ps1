$ErrorActionPreference = 'Stop'

$projectRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$skinDirectory = Join-Path $projectRoot 'images-examples'
$outputPath = Join-Path $projectRoot 'skins.generated.js'

if (-not (Test-Path -LiteralPath $skinDirectory -PathType Container)) {
    throw "Skin directory not found: $skinDirectory"
}

$entries = Get-ChildItem -LiteralPath $skinDirectory -File -Filter '*.png' |
    Sort-Object Name |
    ForEach-Object {
        $bytes = [System.IO.File]::ReadAllBytes($_.FullName)
        [ordered]@{
            name = $_.BaseName
            src = 'data:image/png;base64,' + [Convert]::ToBase64String($bytes)
        }
    }

if ($entries.Count -eq 0) {
    throw "No PNG skins were found in $skinDirectory"
}

$json = ConvertTo-Json -InputObject @($entries) -Compress
$javascript = "// Generated by generate-skins.ps1. Do not edit by hand.`r`nwindow.MINECRAFT_SKINS = $json;`r`n"
[System.IO.File]::WriteAllText($outputPath, $javascript, [System.Text.UTF8Encoding]::new($false))

Write-Host "Generated skins.generated.js with $($entries.Count) skin(s)."
